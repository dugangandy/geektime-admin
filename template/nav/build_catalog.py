def load_web_meta(root):
    """从根目录 catalog.html（官网课程列表存档）解析卡片元数据。

    返回 {归一化名: {author, identity, badge, cover_url, lessons, learners}}。
    """
    f = Path(root) / "catalog.html"
    if not f.is_file():
        return {}
    try:
        raw = f.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return {}
    result = {}

    def put(title, meta):
        """登记元数据，并为「作者 · 课程名」/「课程名（完结）」登记别名（完整标题键优先）。"""
        title = title.strip()
        result[_cat_key(title)] = meta
        if " · " in title:
            alias = _cat_key(title.split(" · ", 1)[1])
            if alias:
                result.setdefault(alias, meta)
        # 官网标题通常不带「（完结）」这类下载标记，去掉括号后缀再登记一次别名
        bare = re.sub(r"[（(][^）)]*[）)]", "", title).strip()
        if bare and bare != title:
            result.setdefault(_cat_key(bare), meta)

    for block in re.split(r"columnItemB_", raw)[1:]:
        mt = re.search(r'course-title">([^<]+)</div>', block)
        mtech = re.search(r'teacher-name">([^<]+)</div>', block)
        if not (mt and mtech):
            continue
        num = re.search(r'course-num">([^<]+)</div>', block)
        num = num.group(1) if num else ""
        lessons = re.search(r'(\d+)\s*讲', num)
        learners = re.search(r'(\d+)\s*人已学习', num)
        ident = re.search(r'identity">([^<]+)</div>', block)
        badge = re.search(r'column-badge"><span[^>]*>([^<]+)</span>', block)
        cover = re.search(r'<img[^>]+class="cover"[^>]*>', block)
        cover = re.search(r'src="([^"]+)"', cover.group(0)).group(1) if cover else ""
        put(html_mod.unescape(mt.group(1)), {
            "author": html_mod.unescape(mtech.group(1)).strip(),
            "identity": html_mod.unescape(ident.group(1)).strip() if ident else "",
            "badge": html_mod.unescape(badge.group(1)).strip() if badge else "",
            "cover_url": cover,
            "lessons": int(lessons.group(1)) if lessons else 0,
            "learners": int(learners.group(1)) if learners else 0,
        })

    if not result:
        # 官网改版后卡片类名哈希可能变化：整页切分失效时退化为标题/讲师/数量配对
        for name, author, num in re.findall(
                r'course-title">([^<]+)</div>.*?teacher-name">([^<]+)</div>'
                r'.*?course-num">([^<]+)</div>', raw, re.S):
            lessons = re.search(r"(\d+)\s*讲", num)
            learners = re.search(r"(\d+)\s*人已学习", num)
            put(html_mod.unescape(name), {
                "author": html_mod.unescape(author).strip(),
                "identity": "", "badge": "", "cover_url": "",
                "lessons": int(lessons.group(1)) if lessons else 0,
                "learners": int(learners.group(1)) if learners else 0,
            })
    return result


def fmt_learners(n):
    if n >= 10000:
        return f"{n / 10000:.1f} 万".replace(".0 万", " 万") + "人已学习"
    return f"{n} 人已学习"

# 课程名自带作者（「XXX的YYY」）时直接提取；非人名命中黑名单则不认
_NAME_AUTHOR_RE = re.compile(r"^([\u4e00-\u9fa5]{2,4})的")
_NAME_AUTHOR_STOP = {"程序员", "互联网人", "技术人员", "每个人"}


def resolve_author(course):
    if course["name"] in AUTHOR_MAP:
        return AUTHOR_MAP[course["name"]]
    if course.get("author"):
        return course["author"]
    m = _NAME_AUTHOR_RE.match(course["name"])
    return m.group(1) if m and m.group(1) not in _NAME_AUTHOR_STOP else ""


def count_chapters(course_dir, content_dir_name):
    """无 reader 时的兜底讲数：统计 html/ 目录下的正文页。"""
    content_dir = course_dir / content_dir_name
    if not content_dir.is_dir():
        return 0
    return sum(1 for p in content_dir.iterdir()
               if p.is_file() and p.suffix.lower() in {".html", ".htm"})


def _cat_key(name):
    """分类映射用的归一化键：忽略空格、标点、全半角斜杠等差异。"""
    return re.sub(r"[\s\-_—–·・.、,，:：|丨｜()（）／/\\]+", "", name).lower()


CAT_KEY_MAP = {_cat_key(k): v for k, v in CATEGORY_MAP.items()}
DIRECTION_KEY_MAP = {_cat_key(k): v for k, v in DIRECTION_MAP.items()}


def resolve_category(name):
    """三级分类：精确映射 -> 归一化映射 -> 关键词 -> misc。返回 (key, 是否命中规则)。"""
    if name in CATEGORY_MAP:
        return CATEGORY_MAP[name], True
    key = _cat_key(name)
    if key in CAT_KEY_MAP:
        return CAT_KEY_MAP[key], True
    low = name.lower()
    for cat, words in KEYWORD_RULES:
        for w in words:
            if w.lower() in low:
                return cat, False
    return "misc", False


def scan(root, content_dir_name, web_meta=None):
    web_meta = web_meta or {}
    courses = []
    for p in sorted(root.iterdir(), key=lambda x: x.name):
        if not p.is_dir() or p.name.startswith(("_", ".")):
            continue
        if p.name.endswith("_old"):      # 重复课程的旧目录备份，不计入总目录
            continue
        if p.name in ("assets", "template"):  # 站点资源 / 模板目录，不是课程
            continue

        reader = p / "reader" / "index.html"
        nav = p / "index.html"
        if reader.is_file():
            href, state = f"{p.name}/reader/index.html", "reader"
        elif nav.is_file():
            href, state = f"{p.name}/index.html", "nav"
        else:
            href, state = "", "none"

        cat, mapped = resolve_category(p.name)
        web = dict(web_meta.get(_cat_key(p.name), {}))
        if not web:
            # 本地目录常带下载标记后缀（如「机器学习40讲（完结）」），去掉括号再匹配一次
            bare = re.sub(r"[（(][^）)]*[）)]", "", p.name).strip()
            if bare and bare != p.name:
                web = dict(web_meta.get(_cat_key(bare), {}))
        web.update({k: v for k, v in META_OVERRIDE.get(p.name, {}).items() if v})
        chapters, js_author = (read_reader_meta(p / "reader") if state == "reader"
                               else (0, ""))
        audios, pdfs, videos = count_media(p)
        courses.append({
            "name": p.name,
            "cat": cat,
            "dir": resolve_direction(p.name, cat),
            "mapped": mapped,
            "state": state,
            "href": href,
            "chapters": chapters,
            "audios": audios,
            "pdfs": pdfs,
            "videos": videos,
            "author": web.get("author", "") or js_author,
            "identity": web.get("identity", ""),
            "badge": web.get("badge", ""),
            "cover_url": web.get("cover_url", ""),
            "lessons": web.get("lessons", 0),
            "learners": web.get("learners", 0),
        })
    return courses


def shade(color, factor=0.72):
    m = re.match(r"^#?([0-9a-f]{6})$", color.strip(), re.I)
    if not m:
        return color
    r, g, b = (int(m.group(1)[i:i + 2], 16) for i in (0, 2, 4))
    return "#{:02x}{:02x}{:02x}".format(int(r * factor), int(g * factor), int(b * factor))


