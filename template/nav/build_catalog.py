def count_media(course_dir):
    """一次 os.walk 统计音频 / PDF / 视频，跳过 reader/、mp4-opt/ 等产物目录。

    旧实现按后缀各跑一次 Path.rglob('*')，整棵课程目录树要遍历、stat 三遍，
    两万多个文件时首页冷启动要数秒。os.walk 复用 scandir 缓存的类型信息，
    不做额外 stat，一遍即可拿到三个计数。
    """
    base = str(course_dir)
    audios = pdfs = videos = 0
    for dirpath, dirnames, filenames in os.walk(base):
        if dirpath == base:
            dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for name in filenames:
            ext = os.path.splitext(name)[1].lower()
            if ext in AUDIO_EXTS:
                audios += 1
            elif ext == ".pdf":
                pdfs += 1
            elif ext in VIDEO_EXTS:
                videos += 1
    return audios, pdfs, videos


def read_reader_meta(reader_dir):
    """一次读取 reader/data/catalog.js，返回 (总讲数, 作者)。"""
    js = reader_dir / "data" / "catalog.js"
    if not js.is_file():
        return 0, ""
    try:
        raw = js.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return 0, ""
    total = re.search(r'"total"\s*:\s*(\d+)', raw)
    author = re.search(r'author["\']?\s*[:=]\s*["\']([^"\']*)', raw)
    return (int(total.group(1)) if total else 0,
            author.group(1).strip() if author else "")


