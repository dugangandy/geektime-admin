def cover_filename(name):
    return re.sub(r"[^\w\u4e00-\u9fa5]+", "_", name).strip("_") or "cover"


def cover_src(course):
    """封面相对路径；无封面返回空串。"""
    if not course.get("cover_file"):
        return ""
    return "assets/covers/" + course["cover_file"]


def fetch_covers(courses, out_dir):
    """把官网封面下载到 <out_dir>/assets/covers/（幂等），并给 course 填 cover_file。"""
    todo = [c for c in courses if c.get("cover_url")]
    if not todo:
        return
    covers = out_dir / "assets" / "covers"
    covers.mkdir(parents=True, exist_ok=True)
    fresh = 0
    seen = {}
    for c in todo:
        fname = cover_filename(c["name"]) + ".webp"
        if fname in seen:
            print(f"[警告] 封面文件名冲突：{seen[fname]} 与 {c['name']} 归一化后同名（{fname}）")
        seen[fname] = c["name"]
        dst = covers / fname
        if not dst.is_file():
            # 官网缩略图参数从 127x167 提到 240x316，保证 2x 屏清晰
            url = c["cover_url"].replace("w_127,h_167", "w_240,h_316")
            try:
                req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
                with urllib.request.urlopen(req, timeout=20) as r, open(dst, "wb") as f:
                    f.write(r.read())
                fresh += 1
            except Exception as e:
                print(f"[警告] 封面下载失败 {c['name']}：{e}")
                continue
        c["cover_file"] = fname
    if fresh:
        print(f"[封面] 新下载 {fresh} 张 → {covers}")


def _build_href(name):
    """按需构建入口（仅服务端动态首页使用；静态副本会降级为不可点）。"""
    return "/__build/" + urllib.parse.quote(name, safe="")


def card_html(course, offline=False):
    """单张课程卡片。offline=True 时 pending/failed 不生成构建链接，避免 file:// 死链。"""
    display = course.get("display") or course["name"]
    name = html_mod.escape(display)
    attrs = html_mod.escape(course["name"], quote=True)

    # 封面区：官方角标 + 封面图（缺图用占位）
    cover = cover_src(course)
    web_badge = ('<span class="web-badge">{}</span>'.format(html_mod.escape(course["badge"]))
                 if course.get("badge") else "")
    if cover:
        cover_html = ('{}<img class="cover" src="{}" alt="" width="102" height="134"'
                      ' loading="lazy" decoding="async">').format(
            web_badge, html_mod.escape(cover, quote=True))
    else:
        cover_html = '{}<span class="cover cover-none">{}</span>'.format(
            web_badge, name[:1])

    # 信息区：标题 / 作者+头衔 / 讲数｜学习人数 / 状态按钮
    author = resolve_author(course)
    identity = ('<span class="identity">{}</span>'.format(html_mod.escape(course["identity"]))
                if course.get("identity") else "")
    teacher = ('<div class="teacher"><b class="author">{}</b>{}</div>'.format(
        html_mod.escape(author), identity)) if author else (
        '<div class="teacher">{}</div>'.format(identity) if identity else "")

    lessons = course.get("lessons") or course.get("chapters") or 0
    audios = course.get("audios", 0)
    videos = course.get("videos", 0)
    num_parts = []
    if lessons:
        num_parts.append(f"{lessons} 讲")
    if not lessons and videos:
        num_parts.append(f"{videos} 集视频")
    elif not lessons and audios:
        num_parts.append(f"{audios} 个音频")
    if course.get("learners_text"):
        num_parts.append(course["learners_text"])
    elif course.get("learners"):
        num_parts.append(fmt_learners(course["learners"]))
    num = '<div class="num">{} </div>'.format(" ｜ ".join(num_parts)) if num_parts else ""

    state = course.get("state") or "none"
    href = course.get("href") or ""
    if state == "reader":
        tag, status, cta_cls, cta_text = "a", "done", "", "开始学习"
    elif state == "nav":
        tag, status, cta_cls, cta_text = "a", "wip", "wip", "更新中"
    elif state == "pending":
        if offline:
            tag, status, cta_cls, cta_text = "div", "pending", "pending", "启动服务后可生成"
        else:
            tag, status, cta_cls, cta_text = "a", "pending", "pending", "生成阅读器"
            href = _build_href(course["name"])
    elif state == "building":
        tag, status, cta_cls, cta_text = "div", "building", "building", "生成中…"
    elif state == "failed":
        if offline:
            tag, status, cta_cls, cta_text = "div", "failed", "failed", "上次生成失败"
        else:
            tag, status, cta_cls, cta_text = "a", "failed", "failed", "重新生成"
            href = _build_href(course["name"])
    else:
        tag, status, cta_cls, cta_text = "div", "none", "off", "敬请期待"
    cta = '<span class="cta{}">{}</span>'.format(
        " " + cta_cls if cta_cls else "", cta_text)

    info = (
        '        <div class="card-info">\n'
        '          <h3 class="card-title">{}</h3>\n'
        '          {}\n'
        '          {}\n'
        '          <div class="card-foot">{}</div>\n'
        '        </div>\n'.format(name, teacher, num, cta)
    )

    if tag == "a" and href:
        return (
            '      <a class="card" href="{}" data-name="{}" data-status="{}" style="--c:{{{{ACCENT}}}}">\n'
            '        <div class="cover-wrap">{}</div>\n'
            '{}'
            '      </a>'.format(html_mod.escape(href, quote=True), attrs, status, cover_html, info)
        )
    return (
        '      <div class="card off" data-name="{}" data-status="{}">\n'
        '        <div class="cover-wrap">{}</div>\n'
        '{}'
        '      </div>'.format(attrs, status, cover_html, info)
    )


def section_html(dkey, courses, offline=False):
    cards = "\n".join(card_html(c, offline=offline) for c in courses)
    return (
        '  <section data-cat="{}">\n'
        '    <h2>{} <span class="count">{} 门</span></h2>\n'
        '    <div class="grid">\n{}\n    </div>\n'
        '  </section>\n'.format(dkey, html_mod.escape(DIRECTION_LABEL[dkey]), len(courses), cards)
    )


# 组内排序权重：可直接打开的在前，其次可一键生成的，再其次导航页，最后是清单占位
_STATE_ORDER = {"reader": 0, "pending": 1, "building": 1, "failed": 1, "nav": 2, "none": 3}


def grouped(courses):
    """按方向固定顺序分组；组内可打开/可生成的在前，各自按学习人数降序、音频数降序、名称升序。"""
    buckets = {}
    for c in courses:
        buckets.setdefault(c["dir"], []).append(c)
    result = []
    for dkey, _label in DIRECTION_ORDER:
        items = buckets.get(dkey)
        if not items:
            continue
        items.sort(key=lambda c: (_STATE_ORDER.get(c.get("state"), 9),
                                  -c.get("learners", 0),
                                  -c.get("audios", 0),
                                  c["name"]))
        result.append((dkey, items))
    return result


def _status_chip(status, label, count, active=False):
    return ('<button class="chip{}" data-status="{}" aria-pressed="{}">{} <span>{}</span></button>'
            .format(" active" if active else "", status,
                    "true" if active else "false", label, count))


def render(courses, title, color="#f66121", offline=False):
    tpl = (Path(__file__).resolve().parent / "catalog_template.html").read_text(encoding="utf-8")

    groups = grouped(courses)
    total_audio = sum(c.get("audios", 0) for c in courses)
    dir_comment = " / ".join(DIRECTION_LABEL[dkey] for dkey, _ in groups)

    # 方向 chips 不设「全部」项（再次点击已选方向即取消），全部数量放在状态行
    chips = "".join(
        '<button class="chip" data-cat="{}" aria-pressed="false">{} <span>{}</span></button>'.format(
            dkey, html_mod.escape(DIRECTION_LABEL[dkey]), len(items))
        for dkey, items in groups
    )

    counts = {}
    for c in courses:
        counts[c.get("state", "none")] = counts.get(c.get("state", "none"), 0) + 1
    status_chips = _status_chip("all", "全部", len(courses), True)
    # chip 的 data-status 与卡片一致：reader→done、nav→wip、pending/building/failed/none 同名
    for status, label, states in (
            ("done", "已完结", ("reader",)),
            ("pending", "待生成", ("pending",)),
            ("building", "生成中", ("building",)),
            ("failed", "生成失败", ("failed",)),
            ("wip", "更新中", ("nav",)),
            ("none", "敬请期待", ("none",))):
        n = sum(counts.get(s, 0) for s in states)
        if n:
            status_chips += _status_chip(status, label, n)

    sections = "\n".join(section_html(dkey, items, offline=offline) for dkey, items in groups)

    # 页头品牌名：标题里 " · " 之前的部分（如「极客时间」）
    brand = title.split(" · ")[0] if " · " in title else title
    footer = "{} · {} 门课程 · {} 个音频".format(brand, len(courses), total_audio)

    out = tpl.replace("{{TITLE}}", html_mod.escape(title))
    out = out.replace("{{BRAND}}", html_mod.escape(brand))
    out = out.replace("{{CATS_COMMENT}}", html_mod.escape(dir_comment))
    out = out.replace("{{CHIPS}}", chips)
    out = out.replace("{{STATUS_CHIPS}}", status_chips)
    out = out.replace("{{SECTIONS}}", sections)
    out = out.replace("{{FOOTER}}", html_mod.escape(footer))
    out = out.replace("{{ACCENT_DARK}}", shade(color))
    out = out.replace("{{ACCENT}}", color)
    return out.replace("<body>", "<body>\n" + MARKER, 1)


