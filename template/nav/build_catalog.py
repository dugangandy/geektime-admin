MANIFEST_NAME = "course_manifest.json"
COURSE_META_NAME = "course.json"
_CONTENT_EXTS = {".html", ".htm", ".md", ".pdf"} | AUDIO_EXTS | VIDEO_EXTS


def load_manifest(path):
    """读取 115 门权威清单；缺失/损坏返回 []。"""
    if not path:
        return []
    p = Path(path)
    if not p.is_file():
        return []
    try:
        data = json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return []
    courses = data.get("courses") if isinstance(data, dict) else None
    return [c for c in (courses or []) if isinstance(c, dict) and c.get("name")]


def load_course_meta(course_dir):
    """读取 <课程>/course.json（可选手工覆写）；损坏时忽略。"""
    f = Path(course_dir) / COURSE_META_NAME
    if not f.is_file():
        return {}
    try:
        data = json.loads(f.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


def has_content(course_dir, content_dir_name="html"):
    """本地课程是否有可构建的正文/附件（跳过 reader/、mp4-opt/ 产物）。"""
    course_dir = Path(course_dir)
    if count_chapters(course_dir, content_dir_name):
        return True
    for p in course_dir.rglob("*"):
        if not p.is_file() or p.suffix.lower() not in _CONTENT_EXTS:
            continue
        rel = p.relative_to(course_dir).parts
        if rel and rel[0] in SKIP_DIRS:
            continue
        return True
    return False


def _direction_from(value):
    """course.json 的 direction 允许写 key（backend）或中文标签（后端/架构）。"""
    if not value:
        return ""
    value = str(value).strip()
    if value in DIRECTION_LABEL:
        return value
    for key, label in DIRECTION_ORDER:
        if value == label:
            return key
    return ""


def _category_from(value):
    if not value:
        return ""
    value = str(value).strip()
    if value in CATEGORY_LABEL:
        return value
    for key, label in CATEGORY_ORDER:
        if value == label:
            return key
    return resolve_category(value)[0]


def _apply_course_meta(course, meta):
    """course.json 覆写：显示名/作者/头衔/分类/方向/讲数/角标/人数/封面（空值忽略）。"""
    if meta.get("title"):
        course["display"] = str(meta["title"]).strip()
    for src, dst in (("author", "author"), ("role", "identity"),
                     ("identity", "identity"), ("badge", "badge")):
        if meta.get(src):
            course[dst] = str(meta[src]).strip()
    if meta.get("lessons"):
        try:
            course["lessons"] = int(meta["lessons"])
        except (TypeError, ValueError):
            pass
    if meta.get("learners_text"):
        course["learners_text"] = str(meta["learners_text"]).strip()
    elif meta.get("learners"):
        try:
            course["learners"] = int(meta["learners"])
        except (TypeError, ValueError):
            pass
    cat = _category_from(meta.get("category"))
    if cat:
        course["cat"] = cat
        course["mapped"] = True
    dkey = _direction_from(meta.get("direction")) or (
        resolve_direction(course["name"], course["cat"]) if cat else "")
    if dkey:
        course["dir"] = dkey
    if meta.get("cover"):
        course["cover_file"] = str(meta["cover"]).strip()


def _manifest_record(m):
    """清单条目 → 与 scan() 同构的课程记录（本地目录存在时会被覆盖）。"""
    name = str(m.get("name")).strip()
    cat = _category_from(m.get("cat")) or resolve_category(name)[0]
    dkey = _direction_from(m.get("dir")) or resolve_direction(name, cat)
    return {
        "name": name, "display": str(m.get("title") or "").strip(),
        "cat": cat, "dir": dkey, "mapped": True,
        "state": "none", "href": "", "chapters": 0,
        "audios": 0, "pdfs": 0, "videos": 0,
        "author": str(m.get("author") or ""),
        "identity": str(m.get("identity") or ""),
        "badge": str(m.get("badge") or ""),
        "cover_url": "", "cover_file": str(m.get("cover") or ""),
        "lessons": int(m.get("lessons") or 0),
        "learners": int(m.get("learners") or 0),
        "learners_text": str(m.get("learners_text") or ""),
        "local": False,
    }


def collect_courses(root, manifest_path=None, content_dir_name="html",
                    build_states=None, course_root=None):
    """合并「本地课程子目录」与「115 门权威清单」，返回统一课程记录。

    root 是服务根（catalog.html、assets/covers 等资源仍放这里）；course_root
    是课程一级目录所在位置，默认等于 root。课程卡片 href 始终是不带前缀的
    相对 URL，在线由服务端映射，离线由 render_index 的 course_prefix 补前缀。

    state：reader / nav / pending（待生成） / building / failed / none（清单占位）。
    元数据优先级：course.json > 现有分类规则与 catalog.html > manifest 补空。
    """
    root = Path(root)
    course_root = Path(course_root) if course_root else root
    build_states = build_states or {}
    web_meta = load_web_meta(root)
    local = scan(course_root, content_dir_name, web_meta)

    by_key = {}
    for c in local:
        meta = load_course_meta(course_root / c["name"])
        if meta:
            _apply_course_meta(c, meta)
        if c["state"] != "reader":                  # 已有 reader 永远优先直接打开
            st = build_states.get(c["name"])
            if st == "building":
                c["state"] = "building"
            elif st == "failed":
                c["state"] = "failed"
            elif c["state"] == "none" and has_content(course_root / c["name"], content_dir_name):
                c["state"] = "pending"              # 本地有内容但还没建 reader
        c["local"] = True
        by_key[_cat_key(c["name"])] = c

    courses = list(local)
    for m in load_manifest(manifest_path):
        key = _cat_key(m["name"])
        target = by_key.get(key)
        if target is not None:
            # 清单只补空，不覆盖本地目录判定与已有元数据
            for field in ("author", "identity", "badge", "learners_text"):
                if not target.get(field) and m.get(field):
                    target[field] = str(m[field])
            if not target.get("cover_file") and m.get("cover"):
                target["cover_file"] = str(m["cover"])
            continue
        rec = _manifest_record(m)
        st = build_states.get(rec["name"])
        if st == "building":
            rec["state"] = "building"
        elif st == "failed":
            rec["state"] = "failed"
        courses.append(rec)
        by_key[key] = rec

    for c in courses:
        # 封面只判断本地文件是否存在；下载只发生在 CLI / 构建任务里
        fname = c.get("cover_file") or (cover_filename(c["name"]) + ".webp")
        c["cover_file"] = fname if (root / "assets" / "covers" / fname).is_file() else ""
        c.setdefault("display", "")
        c.setdefault("learners_text", "")
        c.setdefault("learners", 0)
        c.setdefault("audios", 0)
        c.setdefault("local", False)
    return courses


def course_href_prefix(root, course_root=None):
    """离线静态首页里课程链接的前缀（相对服务根），课程目录外置时才非空。

    同一盘符返回 ``../../课程数据/`` 形式的相对路径；Windows 跨盘符无法用相对
    路径表达，退回 ``file:///...`` 绝对地址（换机器/移动目录后需重新生成副本）。
    """
    root = Path(root).resolve()
    course_root = Path(course_root).resolve() if course_root else root
    if course_root == root:
        return ""
    try:
        rel = os.path.relpath(str(course_root), str(root))
    except ValueError:
        try:
            return course_root.as_uri() + "/"
        except ValueError:
            return ""
    if rel in ("", "."):
        return ""
    return urllib.parse.quote(rel.replace(os.sep, "/") + "/", safe="/")


def render_index(courses, title, color="#f66121", offline=False,
                 course_prefix=""):
    """与服务端共用的渲染入口。offline=True 时待生成卡片降级为不可点。

    course_prefix 只用于离线副本（file:// 双击）；在线首页的 /<课程名>/...
    由 serve.py 的双根映射处理，绝不能带前缀。
    """
    if offline and course_prefix:
        patched = []
        for c in courses:
            c = dict(c)
            href = c.get("href") or ""
            if href and not href.startswith("/"):
                c["href"] = course_prefix + href
            patched.append(c)
        courses = patched
    return render(courses, title, color, offline=offline)


def write_static_index(root, text, out_name="index.html"):
    """原子写静态首页副本（供 file:// 双击）；保留 MARKER 以兼容 CLI 覆盖保护。"""
    root = Path(root)
    dst = root / out_name
    if dst.exists():
        try:
            old = dst.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            old = ""
        if MARKER not in old and "data-cat=" not in old:
            raise RuntimeError("拒绝覆盖非生成物：%s" % dst)
    if MARKER not in text:
        text = text.replace("<body>", "<body>\n" + MARKER, 1)
    tmp = dst.with_name(dst.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, dst)
    return dst


# ---------------------------------------------------------------- 主流程

def main():
    ap = argparse.ArgumentParser(add_help=True, description="生成分类版课程总目录 index.html")
    ap.add_argument("dir", nargs="?", default=None, help="服务根目录，默认脚本目录的上两级")
    ap.add_argument("--data-dir", default=None,
                    help="课程文件夹所在目录，默认与 dir 相同（课程外置时指定）")
    ap.add_argument("--content-dir", default="html", help="课程正文子目录名，默认 html")
    ap.add_argument("--title", default=None, help="页面标题，默认「<根目录名> · 课程总目录」")
    ap.add_argument("--color", default="#f66121", help="主题色，如 #f66121")
    ap.add_argument("--out", default="index.html", help="输出文件名")
    ap.add_argument("--dry-run", action="store_true", help="只打印统计，不写文件")
    ap.add_argument("--no-backup", action="store_true", help="覆盖时不生成 .bak 备份")
    ap.add_argument("--manifest", default=None,
                    help="课程清单（默认 <脚本目录>/course_manifest.json）")
    ap.add_argument("--no-manifest", action="store_true",
                    help="只扫描本地课程子目录，不合并权威清单")
    args = ap.parse_args()

    here = Path(__file__).resolve().parent
    root = Path(args.dir).expanduser().resolve() if args.dir else here.parent.parent
    data_dir = Path(args.data_dir).expanduser().resolve() if args.data_dir else root
    if not root.is_dir():
        sys.exit(f"[错误] 目录不存在：{root}")
    if not data_dir.is_dir():
        sys.exit(f"[错误] 课程数据目录不存在：{data_dir}")

    manifest_path = None
    if not args.no_manifest:
        manifest_path = (Path(args.manifest).expanduser().resolve()
                         if args.manifest else here / MANIFEST_NAME)
    courses = collect_courses(root, manifest_path, args.content_dir,
                              course_root=data_dir)
    if not courses:
        sys.exit(f"[错误] {data_dir} 下没有课程子目录")

    fetch_covers(courses, root)

    title = args.title or f"{root.name} · 课程总目录"
    page = render_index(courses, title, args.color, offline=True,
                        course_prefix=course_href_prefix(root, data_dir))

    groups = grouped(courses)
    local_n = sum(1 for c in courses if c.get("local"))
    print(f"[扫描] {data_dir}")
    print(f"       清单 {len(courses)} 门（本地目录 {local_n} 门），"
          f"音频合计 {sum(c.get('audios', 0) for c in courses)} 个")
    for dkey, items in groups:
        print(f"       {DIRECTION_LABEL[dkey]:<8} {len(items):>3} 门")

    unknown = [c["name"] for c in courses if c.get("local") and not c["mapped"] and c["cat"] == "misc"]
    if unknown:
        print(f"[警告] {len(unknown)} 门课程无法自动分类，已放入「未分类」，请补 CATEGORY_MAP：")
        for n in unknown:
            print(f"       - {n}")

    if args.dry_run:
        print("[dry-run] 未写入文件")
        return

    out_path = root / args.out
    if out_path.exists():
        old = out_path.read_text(encoding="utf-8", errors="ignore")
        # 只覆盖本工具生成的或已是分类格式（含 data-cat）的文件，避免误伤别的手写页面
        if MARKER not in old and "data-cat=" not in old:
            sys.exit(f"[错误] {out_path} 已存在且不是分类目录格式，已停止以免覆盖")
        # 首次接管（旧文件不是本工具生成的）才备份，避免每次运行都堆备份
        if MARKER not in old and not args.no_backup:
            bak = out_path.with_name(out_path.name + ".bak")
            if bak.exists():
                stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
                bak = out_path.with_name(f"{out_path.name}.bak.{stamp}")
            shutil.copyfile(out_path, bak)
            print(f"[备份] {bak}")

    write_static_index(root, page, args.out)
    print(f"[完成] {out_path}")

    # 顶栏官方 logo：与阅读器模板共用同一张图，复制到 <输出目录>/assets/logo.png
    logo_src = Path(__file__).resolve().parent.parent / "reader" / "assets" / "logo.png"
    if logo_src.is_file():
        dst = out_path.parent / "assets" / "logo.png"
        dst.parent.mkdir(parents=True, exist_ok=True)
        if not dst.is_file() or dst.read_bytes() != logo_src.read_bytes():
            shutil.copyfile(logo_src, dst)
            print(f"[logo] {dst}")
    else:
        print(f"[警告] 找不到 logo：{logo_src}（顶栏会退化为文字）")


if __name__ == "__main__":
    main()
