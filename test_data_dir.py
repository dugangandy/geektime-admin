#!/usr/bin/env python3
"""课程数据目录外置（--data-dir / GK_DATA_DIR）的自测（纯标准库）。

root 只放模板/清单/封面/口令/静态首页，data_dir 只放各门课程的子目录。
覆盖：双根静态路由、动态首页、离线副本前缀、按需构建、手机端 API、
路径穿越与敏感扩展、参数优先级、无效目录报错、口令子命令。

运行：python -m unittest test_data_dir -v
"""
import contextlib
import http.client
import io
import json
import os
import shutil
import sys
import tempfile
import threading
import time
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import serve  # noqa: E402

PASSWORD = "correct horse battery staple"
COURSE = "Course A"


def _lesson_page(data):
    payload = json.dumps(data, ensure_ascii=True, separators=(",", ":"))
    return (
        '<!doctype html><html><head><meta charset="utf-8"></head><body>'
        '<script type="application/json" id="lesson-data">%s</script>'
        '</body></html>' % payload
    )


def _catalog(title, author, chapters):
    doc = {"title": title, "author": author,
           "total": sum(len(c["items"]) for c in chapters),
           "chapters": chapters}
    return "window.COURSE = %s;" % json.dumps(doc, ensure_ascii=False)


FAKE_BUILD_PY = '''\
import os
import sys

course = sys.argv[1]
out = os.path.join(course, "reader")
os.makedirs(out, exist_ok=True)
with open(os.path.join(out, "index.html"), "w", encoding="utf-8") as f:
    f.write("<html>DATA-BUILT</html>")
'''


class DataDirCase(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls._orig_log = serve.Handler.log_message
        serve.Handler.log_message = lambda *a, **k: None

    @classmethod
    def tearDownClass(cls):
        serve.Handler.log_message = cls._orig_log

    def setUp(self):
        self._cwd = os.getcwd()
        self.root = tempfile.mkdtemp(prefix="gk-datadir-root-")
        self.data_dir = tempfile.mkdtemp(prefix="gk-datadir-data-")
        self._make_tree()
        serve.AuthStore(os.path.join(self.root, "auth.json")).set_password(
            PASSWORD, iterations=1000)
        self.cfg = serve.parse_args([
            "0", self.root, "--bind", "127.0.0.1",
            "--data-dir", self.data_dir, "--no-auth",
        ])
        self.httpd = serve.create_server(self.cfg)
        self.assertIsNotNone(self.httpd.site, "动态首页未启用")
        self.assertIsNotNone(self.httpd.build_queue, "按需构建队列未启用")
        self.assertIsNotNone(self.httpd.api, "手机端 API 未启用")
        self.port = self.httpd.server_address[1]
        self.thread = threading.Thread(target=self.httpd.serve_forever, daemon=True)
        self.thread.start()

    def tearDown(self):
        self.httpd.shutdown()
        self.httpd.server_close()
        self.thread.join(timeout=2)
        os.chdir(self._cwd)
        shutil.rmtree(self.root, ignore_errors=True)
        shutil.rmtree(self.data_dir, ignore_errors=True)

    # ---------------------------------------------------------------- 构造
    def _make_tree(self):
        def put(base, rel, data):
            path = os.path.join(base, rel)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            if isinstance(data, bytes):
                with open(path, "wb") as f:
                    f.write(data)
            else:
                with open(path, "w", encoding="utf-8") as f:
                    f.write(data)

        # root：模板 / 清单 / 封面 / 口令 / 静态首页
        os.makedirs(os.path.join(self.root, "_导航模版"), exist_ok=True)
        for name in ("build_catalog.py", "catalog_template.html"):
            shutil.copy2(os.path.join(HERE, "_导航模版", name),
                         os.path.join(self.root, "_导航模版", name))
        put(self.root, "_导航模版/course_manifest.json", json.dumps(
            {"version": 1, "courses": [
                {"name": COURSE, "dir": "backend", "author": "Alice",
                 "lessons": 1, "cover": "Course A.webp"}]},
            ensure_ascii=False))
        os.makedirs(os.path.join(self.root, "_阅读器模板"), exist_ok=True)
        put(self.root, "_阅读器模板/build.py", FAKE_BUILD_PY)
        put(self.root, "assets/covers/Course A.webp", b"RIFFxxxxWEBPVP8 ")
        put(self.root, "site.txt", "ROOT-ASSET")
        put(self.root, "index.html",
            "<!doctype html><html><body>ROOT-INDEX"
            "<!-- generated by build_catalog.py --></body></html>")
        # root 下同名课程目录：外置后不应被服务，用于验证双根隔离
        put(self.root, "Course A/reader/index.html", "ROOT-COURSE-PAGE")
        put(self.root, "Course A/only-in-root.txt", "ROOT-ONLY")

        # data_dir：只放课程子目录
        put(self.data_dir, "Course A/reader/index.html", "DATA-COURSE-PAGE")
        put(self.data_dir, "Course A/only-in-data-dir.txt", "DATA-ONLY")
        put(self.data_dir, "Course A/secret.json", "{}")
        put(self.data_dir, "Course A/00-audio.mp3", b"\x00" * 5000)
        put(self.data_dir, "Course A/00-doc.pdf", b"%PDF-1.4" + b"\x00" * 3000)
        put(self.data_dir, "Course A/reader/data/catalog.js", _catalog(
            "Course A", "Alice", [{"name": "基础篇", "items": [
                {"i": 0, "label": "00 | 开场", "date": "2024-01-01",
                 "dur": "10:00"}]}]))
        put(self.data_dir, "Course A/reader/pages/000.html", _lesson_page({
            "total": 1, "kind": "kind-simple", "course": "Course A",
            "meta": "", "sub": "", "idx": 0, "title": "00 | 开场",
            "cover": "", "duration": "10:00",
            "audio": "../../00-audio.mp3", "pdf": "../../00-doc.pdf",
            "body": "<p>hello</p>",
        }))
        # 无 reader：供按需构建测试
        put(self.data_dir, "Course B/html/001.html", "<p>lesson</p>")

    # ---------------------------------------------------------------- 助手
    def get(self, path, port=None):
        conn = http.client.HTTPConnection(
            "127.0.0.1", port if port is not None else self.port, timeout=10)
        try:
            conn.request("GET", path)
            resp = conn.getresponse()
            return resp.status, resp.read()
        finally:
            conn.close()

    def _extra_server(self, cfg):
        """起一个不共享主服务配置的临时服务，返回 (httpd, thread)。"""
        httpd = serve.create_server(cfg)
        thread = threading.Thread(target=httpd.serve_forever, daemon=True)
        thread.start()
        return httpd, thread

    @staticmethod
    def _stop_extra(httpd, thread):
        httpd.shutdown()
        httpd.server_close()
        thread.join(timeout=2)

    # ---------------------------------------------------------------- 用例
    def test_default_data_dir_equals_root(self):
        """不指定参数时完全沿用旧行为。"""
        cfg = serve.parse_args(["0", self.root, "--no-auth"])
        httpd = serve.create_server(cfg)
        try:
            self.assertEqual(httpd.root, os.path.abspath(self.root))
            self.assertEqual(httpd.data_dir, os.path.abspath(self.root))
        finally:
            httpd.server_close()

    def test_env_var_and_cli_priority(self):
        """GK_DATA_DIR 生效，且 --data-dir 优先于环境变量。"""
        old = os.environ.get("GK_DATA_DIR")
        os.environ["GK_DATA_DIR"] = self.data_dir
        try:
            httpd = serve.create_server(
                serve.parse_args(["0", self.root, "--no-auth"]))
            try:
                self.assertEqual(httpd.data_dir, os.path.abspath(self.data_dir))
            finally:
                httpd.server_close()

            httpd = serve.create_server(serve.parse_args(
                ["0", self.root, "--no-auth", "--data-dir", self.root]))
            try:
                self.assertEqual(httpd.data_dir, os.path.abspath(self.root))
            finally:
                httpd.server_close()
        finally:
            if old is None:
                os.environ.pop("GK_DATA_DIR", None)
            else:
                os.environ["GK_DATA_DIR"] = old

    def test_invalid_data_dir_fails_fast(self):
        cfg = serve.parse_args([
            "0", self.root, "--no-auth", "--data-dir",
            os.path.join(self.root, "no-such-course-dir")])
        with self.assertRaises(SystemExit) as cm:
            serve.create_server(cfg)
        self.assertEqual(cm.exception.code, 2)

    def test_password_subcommands_ignore_data_dir(self):
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            rc = serve.main(["--gen-password", "--data-dir",
                             os.path.join(self.root, "no-such-course-dir")])
        self.assertEqual(rc, 0)
        self.assertTrue(buf.getvalue().strip())

    def test_static_routes_external_course_and_root_assets(self):
        status, body = self.get("/Course%20A/reader/index.html")
        self.assertEqual(status, 200)
        self.assertEqual(body, b"DATA-COURSE-PAGE", "课程文件应来自 data_dir")

        status, body = self.get("/Course%20A/only-in-data-dir.txt")
        self.assertEqual(status, 200)
        self.assertEqual(body, b"DATA-ONLY")

        status, body = self.get("/site.txt")
        self.assertEqual(status, 200)
        self.assertEqual(body, b"ROOT-ASSET")

        status, body = self.get("/assets/covers/Course%20A.webp")
        self.assertEqual(status, 200)
        self.assertEqual(body, b"RIFFxxxxWEBPVP8 ")

    def test_root_course_dir_is_not_served_and_no_traversal(self):
        # root 下存在同名课程目录，但外置后不应被读到
        status, _ = self.get("/Course%20A/only-in-root.txt")
        self.assertEqual(status, 404)

        # `..` 由标准库规范化，绝不能读到服务根之外的文件
        outside_name = "gk-outside-%s.txt" % os.path.basename(self.root)
        outside = os.path.join(os.path.dirname(self.root), outside_name)
        with open(outside, "w", encoding="utf-8") as f:
            f.write("OUTSIDE")
        self.addCleanup(lambda: os.path.isfile(outside) and os.remove(outside))
        for path in ("/../" + outside_name,
                     "/Course%20A/../../../" + outside_name):
            status, _ = self.get(path)
            self.assertEqual(status, 404, path)
        # 规范化后落回 root 自身的资源是允许的，不算逃逸
        status, body = self.get("/Course%20A/../../site.txt")
        self.assertEqual(status, 200)
        self.assertEqual(body, b"ROOT-ASSET")

        # 敏感扩展规则基于 URL，与数据目录无关
        self.assertTrue(serve.Handler._is_sensitive(
            "/Course%20A/secret.json"))
        self.assertTrue(serve.Handler._is_sensitive(
            "/Course%20A/.git/config"))

    def test_sensitive_files_blocked_with_auth_enabled(self):
        httpd, thread = self._extra_server(serve.parse_args(
            ["0", self.root, "--bind", "127.0.0.1",
             "--data-dir", self.data_dir]))
        try:
            status, _ = self.get("/Course%20A/secret.json",
                                 httpd.server_address[1])
            self.assertEqual(status, 404)
        finally:
            self._stop_extra(httpd, thread)

    def test_dynamic_home_lists_external_courses(self):
        names = [c["name"] for c in self.httpd.site.courses()]
        self.assertIn("Course A", names)
        self.assertIn("Course B", names)
        status, body = self.get("/")
        self.assertEqual(status, 200)
        html = body.decode("utf-8")
        self.assertIn("Course A", html)
        # 在线首页链接保持 /<课程名>/... 形态，不带离线副本的相对前缀
        self.assertIn('href="Course A/reader/index.html"', html)
        prefix = self.httpd.site.catalog.course_href_prefix(
            self.root, self.data_dir)
        self.assertNotIn('href="%sCourse A' % prefix, html)

    def test_offline_static_copy_has_data_dir_prefix(self):
        site = self.httpd.site
        prefix = site.catalog.course_href_prefix(self.root, self.data_dir)
        self.assertTrue(prefix.startswith("../"), prefix)
        site._dirty = True
        site._last_static = 0.0
        site._refresh_static(site.courses())
        with open(os.path.join(self.root, "index.html"), encoding="utf-8") as f:
            html = f.read()
        self.assertIn('href="%sCourse A/reader/index.html"' % prefix, html)

    def test_autobuild_writes_reader_into_data_dir(self):
        queue = self.httpd.build_queue
        allowed = queue.allowed()
        self.assertIn("Course B", allowed)
        self.assertNotIn("_导航模版", allowed)
        real, state = queue.request("Course B")
        self.assertIsNotNone(real)
        for _ in range(100):
            info = queue.status(real)
            if info["state"] in ("ready", "failed"):
                break
            time.sleep(0.05)
        self.assertEqual(info["state"], "ready", info.get("detail"))
        self.assertTrue(os.path.isfile(os.path.join(
            self.data_dir, "Course B", "reader", "index.html")))
        self.assertFalse(os.path.isfile(os.path.join(
            self.root, "Course B", "reader", "index.html")))

    def test_mobile_api_media_urls_use_data_dir(self):
        api = self.httpd.api
        courses = api.index.courses()
        self.assertEqual([c["name"] for c in courses], [COURSE])
        course = courses[0]
        self.assertEqual(os.path.dirname(course["path"]),
                         os.path.abspath(self.data_dir))
        media = api._media(course, 0)
        self.assertEqual(media["audio_url"], "/Course%20A/00-audio.mp3")
        self.assertEqual(media["pdf_url"], "/Course%20A/00-doc.pdf")
        self.assertEqual(api._resolve_media(course, "../../00-audio.mp3"),
                         "/Course%20A/00-audio.mp3")
        self.assertNotIn("..", media["audio_url"])


if __name__ == "__main__":
    unittest.main()
