#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
课程导航页生成器
================

把「课程目录（根目录放音频 mp3，html/ 子目录放章节正文）」自动生成一个
离线可用的 index.html 导航页（纯静态，双击用浏览器打开即可，不需要服务器）。

用法
----
    # 最简：在当前课程目录下运行
    python build_nav.py

    # 指定课程目录（默认标题取目录名）
    python build_nav.py "E:/.../极客时间/MySQL实战45讲"

    # 自定义标题 / 副标题 / 主题色 / 输出文件名
    python build_nav.py <课程目录> --title "MySQL实战45讲" --subtitle "极客时间专栏 · 学习资料导航" \
        --color "#e67e22" --out index.html

    # 正文目录不叫 html、音频在别的目录、不要音频功能
    python build_nav.py <课程目录> --content-dir 正文 --audio-dir audio --no-audio

参数
----
    dir             课程根目录（默认：当前工作目录）
    --content-dir   章节正文所在子目录名，默认 html
    --audio-dir     音频所在目录，默认课程根目录（音频相对该目录匹配）
    --title         导航页大标题，默认取课程目录名
    --subtitle      导航页副标题，默认 "学习资料导航"
    --color         主题色（十六进制），默认 Go 蓝 #00add8
    --out           输出文件名，默认 index.html（已存在且非本工具生成时先备份为 *.bak）
    --no-audio      不生成音频播放功能
    --no-spacing    不在中英文之间自动补空格

分组规则（可直接在脚本里改 GROUP_RULES / SPECIAL_IN_NUM）
--------------------------------------------------
    编号开头（01 xxx / 01讲xxx / 第10讲 xxx / 10.xxx） -> 正文章节（按序号排序）
    其余按关键词归类：开篇 / 导读 / 加餐 / 复习 / 彩蛋 / 测试 / 尾声 / 其他
    完全无编号的文件会落到「其他」，只能靠搜索定位
"""

import argparse
import html as html_mod
import os
import re
import shutil
import sys
from pathlib import Path
from urllib.parse import quote

# ---------------------------------------------------------------- 配置区

# 非编号开头的文件名 -> 分组（按顺序匹配，第一个命中生效）
GROUP_RULES = [
    ("开篇", ("开篇词", "开篇", "发刊词", "先导篇")),
    ("导读", ("导读", "序言", "前言", "序章", "学前必读", "学习攻略", "食用指南", "学习指南")),
    ("加餐", ("加餐", "特别放送", "特别福利", "答疑", "直播", "返场", "大咖助阵",
              "用户故事", "编辑手记", "新书首发", "热点观察", "课外阅读", "课程迭代",
              "春节策划", "元旦", "专栏学得苦", "练习Sample")),
    ("复习", ("划重点", "即学即练", "复习卡", "复习课", "总复习", "期中复习", "期末复习", "复习")),
    ("彩蛋", ("彩蛋", "福利", "番外")),
    ("测试", ("测试", "自测", "结课", "期末考试", "期中考试", "满分试卷", "习题", "试题", "考试")),
    ("尾声", ("尾声", "结束语", "结业", "后记")),
]


# 分组显示顺序：正文插在指定位置，未命中的归「其他」（最后）
GROUP_ORDER = ["开篇", "导读", "正文", "加餐", "复习", "彩蛋", "测试", "尾声", "其他"]

# 数字开头，但含有这些关键词时改归到对应分组
# 注意：这里不放「测试」这种常见词，否则 "23 测试的基本规则" 会被误分走
SPECIAL_IN_NUM = [
    ("加餐", ("加餐", "特别放送", "答疑", "直播", "返场")),
    ("彩蛋", ("彩蛋", "福利")),
    ("测试", ("结课测试", "期末测试", "结课", "自测", "毕业测试")),
    ("尾声", ("尾声", "结束语", "结业")),
]

AUDIO_EXTS = {".mp3", ".m4a", ".aac", ".flac", ".wav", ".ogg", ".opus"}

# 章节序号：兼容「01 xxx」「01讲xxx」「第10讲 xxx」「10.xxx」「01工作区」
NUM_RE = re.compile(
    r"^\s*(?:第\s*(?P<a>\d+)\s*[讲节课章篇集]"
    r"|(?P<b>\d+)\s*[讲节课章篇集]"
    r"|(?P<c>\d+)\s*[\.、\-_|:：｜]"
    r"|(?P<d>\d+)\s+"
    r"|(?P<e>\d+)(?=\s*[\u4e00-\u9fa5]))"
    r"\s*(?P<rest>.*)$"
)
SPACE_A = re.compile(r"(?<=[A-Za-z0-9])(?=[\u4e00-\u9fa5])")
SPACE_B = re.compile(r"(?<=[\u4e00-\u9fa5])(?=[A-Za-z0-9])")
TITLE_RE = re.compile(r"<title[^>]*>(.*?)</title>", re.S | re.I)
MARKER = "<!-- generated by build_nav.py -->"


# ---------------------------------------------------------------- 工具函数

def spacing(text):
    """中英文之间补一个空格：'工作区和GOPATH' -> '工作区和 GOPATH'"""
    text = SPACE_A.sub(" ", text)
    text = SPACE_B.sub(" ", text)
    return re.sub(r"\s{2,}", " ", text).strip()


def normalize(name):
    """用于音频与正文的配对：忽略空格、大小写、中英文括号差异"""
    table = {ord("（"): "(", ord("）"): ")", ord("｜"): "|", ord("－"): "-"}
    return re.sub(r"\s+", "", name.translate(table)).lower()


def read_html_title(path):
    try:
        raw = path.read_bytes()[:8192].decode("utf-8", "ignore")
    except OSError:
        return ""
    m = TITLE_RE.search(raw)
    if not m:
        return ""
    return re.sub(r"\s+", " ", html_mod.unescape(m.group(1))).strip()


def split_num(stem):
    """拆出序号："第10讲 xxx" -> ("10", "xxx")；不是编号开头返回 None"""
    m = NUM_RE.match(stem)
    if not m:
        return None
    num = m.group("a") or m.group("b") or m.group("c") or m.group("d") or m.group("e")
    return num, m.group("rest")


def classify(stem):
    """返回 (分组名, 序号文本, 去掉前缀后的标题文本)"""
    parts = split_num(stem)
    if parts:
        num, rest = parts
        # 只看去掉序号后的前 5 个字符：命中 "加餐｜xxx" 这类性质词，
        # 又不会把 "12 热点问题答疑：…" 这类正课误分走
        head = rest[:5]
        for group, kws in SPECIAL_IN_NUM:
            for kw in kws:
                if kw in head:
                    tail = re.sub(r"^\s*" + re.escape(kw) + r"\s*[\.、\-_|:：｜\s]*", "", rest)
                    return group, kw, tail
        return "正文", num, rest
    for group, kws in GROUP_RULES:
        for kw in kws:
            if kw in stem:
                rest = re.sub(r"^\s*" + re.escape(kw) + r"\s*[\.、\-_|:：｜\s]*", "", stem)
                return group, kw, rest
    return "其他", "", stem


def collect(content_dir, audio_dir, use_audio, do_spacing):
    """扫描正文与音频，返回按分组排好序的条目列表"""
    audios = {}
    if use_audio and audio_dir.is_dir():
        for p in audio_dir.iterdir():
            if p.is_file() and p.suffix.lower() in AUDIO_EXTS:
                audios[normalize(p.stem)] = p

    items = []
    used_audio = set()
    for p in sorted(content_dir.iterdir(), key=lambda x: x.name):
        if not p.is_file() or p.suffix.lower() not in {".html", ".htm"}:
            continue
        title = read_html_title(p) or p.stem
        group, num, text = classify(p.stem)
        if not text:
            text = title
        if do_spacing:
            text, num = spacing(text), spacing(num)
        href = quote(f"{content_dir.name}/{p.name}")

        audio_path = audios.get(normalize(p.stem))
        audio_attr = ""
        if audio_path:
            used_audio.add(normalize(p.stem))
            audio_attr = quote(
                os.path.relpath(audio_path, content_dir.parent).replace("\\", "/")
            )

        items.append({
            "group": group,
            "num": num,
            "text": text,
            "href": href,
            "audio": audio_attr,
            "sort": (int(num) if num.isdigit() else 0, p.name),
        })

    items.sort(key=lambda it: (GROUP_ORDER.index(it["group"]) if it["group"] in GROUP_ORDER else 99,
                               it["sort"]))
    unused = [v.name for k, v in audios.items() if k not in used_audio]
    return items, unused


def render(items, title, subtitle, color, footer):
    """按分组渲染 section / card 的 HTML"""
    tpl = (Path(__file__).resolve().parent / "template.html").read_text(encoding="utf-8")

    groups = []
    for g in GROUP_ORDER:
        members = [it for it in items if it["group"] == g]
        if not members:
            continue
        cards = []
        for it in members:
            audio_html = ""
            cls = "card"
            if it["audio"]:
                cls += " has-audio"
                audio_html = (
                    '<span class="play" role="button" tabindex="-1" data-src="{}" '
                    'data-title="{}" title="播放音频">&#9654;</span>'
                ).format(it["audio"], html_mod.escape(f"{it['num']} {it['text']}".strip(), quote=True))
            num_html = f'<span class="num">{html_mod.escape(it["num"])}</span>' if it["num"] else ""
            cards.append(
                '      <a class="{}" href="{}">{}{}{}</a>'.format(
                    cls, it["href"], num_html, html_mod.escape(it["text"]), audio_html
                )
            )
        groups.append(
            '  <section>\n'
            '    <h2>{} <span class="count">{} 篇</span></h2>\n'
            '    <div class="grid">\n{}\n    </div>\n'
            '  </section>\n'.format(html_mod.escape(g), len(members), "\n".join(cards))
        )

    accent_dark = shade(color)
    out = tpl.replace("{{TITLE}}", html_mod.escape(title))
    out = out.replace("{{SUBTITLE}}", html_mod.escape(subtitle))
    out = out.replace("{{ACCENT}}", color)
    out = out.replace("{{ACCENT_DARK}}", accent_dark)
    out = out.replace("{{SECTIONS}}", "\n".join(groups))
    out = out.replace("{{FOOTER}}", html_mod.escape(footer))
    return out.replace("<body>", "<body>\n" + MARKER, 1)


def shade(color, factor=0.72):
    """把主题色压暗，做渐变与强调色"""
    m = re.match(r"^#?([0-9a-f]{6})$", color.strip(), re.I)
    if not m:
        return color
    r, g, b = (int(m.group(1)[i:i + 2], 16) for i in (0, 2, 4))
    return "#{:02x}{:02x}{:02x}".format(int(r * factor), int(g * factor), int(b * factor))


# ---------------------------------------------------------------- 主流程

def main():
    ap = argparse.ArgumentParser(add_help=True, description="生成课程导航页 index.html")
    ap.add_argument("dir", nargs="?", default=".", help="课程根目录（默认当前目录）")
    ap.add_argument("--content-dir", default="html", help="章节正文子目录名，默认 html")
    ap.add_argument("--audio-dir", default=None, help="音频目录，默认课程根目录")
    ap.add_argument("--title", default=None, help="导航页标题，默认取目录名")
    ap.add_argument("--subtitle", default="学习资料导航", help="导航页副标题")
    ap.add_argument("--color", default="#00add8", help="主题色，如 #e67e22")
    ap.add_argument("--out", default="index.html", help="输出文件名")
    ap.add_argument("--no-audio", action="store_true", help="不生成音频播放功能")
    ap.add_argument("--no-spacing", action="store_true", help="不自动在中英文之间补空格")
    args = ap.parse_args()

    root = Path(args.dir).expanduser().resolve()
    if not root.is_dir():
        sys.exit(f"[错误] 课程目录不存在：{root}")
    content_dir = root / args.content_dir
    if not content_dir.is_dir():
        sys.exit(f"[错误] 找不到正文目录：{content_dir}（可用 --content-dir 指定）")
    audio_dir = Path(args.audio_dir).expanduser().resolve() if args.audio_dir else root

    title = args.title or root.name
    items, unused = collect(content_dir, audio_dir, not args.no_audio, not args.no_spacing)
    if not items:
        sys.exit(f"[错误] {content_dir} 下没有 html 文件")

    audio_count = sum(1 for it in items if it["audio"])
    footer = f"{title} · 共 {len(items)} 篇"
    if audio_count:
        footer += f" · 含 {audio_count} 个音频"
    footer += " · 学习资料导航页"

    page = render(items, title, args.subtitle, args.color, footer)

    out_path = root / args.out
    if out_path.exists() and MARKER not in out_path.read_text(encoding="utf-8", errors="ignore"):
        bak = out_path.with_name(out_path.name + ".bak")
        i = 1
        while bak.exists():
            i += 1
            bak = out_path.with_name(f"{out_path.name}.bak{i}")
        shutil.copy2(out_path, bak)
        print(f"[提示] 已备份原文件 -> {bak.name}")
    out_path.write_text(page, encoding="utf-8")

    print(f"[完成] {out_path}")
    print(f"       标题：{title}    分组：", end="")
    print("、".join(f"{g}({sum(1 for i in items if i['group'] == g)})" for g in GROUP_ORDER
                    if any(i["group"] == g for i in items)))
    print(f"       正文 {len(items)} 篇，匹配音频 {audio_count} 个")
    if unused:
        print(f"[提示] {len(unused)} 个音频未匹配到同名正文：{unused[:5]}"
              f"{' …' if len(unused) > 5 else ''}")


if __name__ == "__main__":
    main()
